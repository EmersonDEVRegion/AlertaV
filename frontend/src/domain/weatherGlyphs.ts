/**
 * El glifo de un aviso por su `fenomeno` (texto de la DMC: «Tormentas
 * Eléctricas», «Viento», «Precipitaciones», «Altas Temperaturas», «Nevadas»).
 * `null` si no se reconoce: la franja usa entonces el triángulo de alerta.
 */
export function weatherGlyphFor(fenomeno: string | null): WeatherGlyphId | null {
  if (!fenomeno) return null
  const t = fenomeno
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
  if (t.includes('tormenta')) return 'lightning'
  if (t.includes('viento')) return 'wind'
  if (t.includes('nev') || t.includes('nieve')) return 'snow'
  if (t.includes('precipit') || t.includes('lluvi')) return 'rain'
  if (t.includes('temperatura') || t.includes('calor') || t.includes('helada') || t.includes('frio'))
    return 'heat'
  return null
}
